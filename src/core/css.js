import { allUtilities, resolveButtons, buttonRules } from "./resolve.js";

export const BREAKPOINTS = { md: 768, lg: 992 };

const selector = (classes) => classes.map((c) => `.${c}`).join("");
const decl = (style, tokens, indent) =>
  Object.entries(style).map(([k, v]) => `${indent}${k}: ${tokens.css(v)};`).join("\n");

/** Mobile-first CSS for a list of rules. */
export function rulesToCss(rules, tokens) {
  let css = rules.map((r) => `${selector(r.classes)} {\n${decl(r.style.base || {}, tokens, "  ")}\n}`).join("\n");
  for (const bp of ["md", "lg"]) {
    const block = rules
      .filter((r) => r.style[bp] && Object.keys(r.style[bp]).length)
      .map((r) => `  ${selector(r.classes)} {\n${decl(r.style[bp], tokens, "    ")}\n  }`);
    if (block.length) css += `\n\n@media (min-width: ${BREAKPOINTS[bp]}px) {\n${block.join("\n")}\n}`;
  }
  return css + "\n";
}

/** Shared stylesheets for code targets: tokens, framework utilities, buttons. */
export function sharedCss(ctx) {
  const utilities = Object.entries(allUtilities(ctx)).map(([name, style]) => ({ classes: [name], style }));
  const buttons = resolveButtons(ctx);
  return {
    "tokens.css": `/* Generated by Component Forge. Override values in forge.config.js → tokens. */\n${ctx.tokens.rootCss()}`,
    "utilities.css": utilities.length
      ? `/* ${ctx.framework.label} utilities. Skip this file if your project already defines them. */\n${rulesToCss(utilities, ctx.tokens)}`
      : `/* ${ctx.framework.label} has no global utilities; layout styles live in each component. */\n`,
    "buttons.css": buttons.styles === "none"
      ? `/* classes.button.styles is "none": your project styles ${Object.values(buttons.chains).map((c) => c.join(".")).join(", ")}. */\n`
      : `/* Button classes from forge.config.js → classes.button. */\n${rulesToCss(buttonRules(buttons), ctx.tokens)}`,
  };
}
